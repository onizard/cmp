const REPLI = 'fr';

/** Traduit une cle, en remplissant les {trous}. */
function tr(lang, cle, vars) {
  const dict = TEXTES[lang] || TEXTES[REPLI];
  const brut = dict[cle] !== undefined ? dict[cle] : TEXTES[REPLI][cle];
  if (brut === undefined) return cle;
  return String(brut).replace(/\{(\w+)\}/g, (_, k) =>
    vars && k in vars ? String(vars[k]) : `{${k}}`,
  );
}

/**
 * Le libelle d'une recompense dans la langue du destinataire. Sans cle
 * connue — souhait sur mesure, recompense ajoutee a la main — on garde le
 * libelle tel qu'il est en base.
 */
function libelle(lang, cle, repli) {
  const dict = CATALOGUE[lang] || CATALOGUE[REPLI];
  return (cle && (dict[cle] || CATALOGUE[REPLI][cle])) || repli || '';
}

module.exports = { tr, libelle, LANGUES: Object.keys(TEXTES) };
